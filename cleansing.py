# ========================================================
# ENGINE: MEMBERSIHKAN DATA ERAT / ERROR FORMAT DI EXCEL
# ========================================================
# Jika kolom 'rh_avg' ada di dalam file Anda, kita bersihkan secara otomatis
if 'rh_avg' in df.columns:
    # Mengubah seluruh kolom menjadi teks untuk deteksi aman
    df['rh_avg'] = df['rh_avg'].astype(str).str.strip()

    # Fungsi cerdas untuk memilah angka
    def fix_rh_values(val):
        try:
            # Mengubah string ke float numerik murni
            num = float(val)
            # Jika angka bernilai ribuan (palsu karena salah format ekspor)
            if num >= 1000:
                return num / 10000
            return num
        except ValueError:
            return val

    df['rh_avg'] = df['rh_avg'].apply(fix_rh_values)

# Jika kolom 'tt_air_avg' juga ingin dibersihkan secara otomatis
if 'tt_air_avg' in df.columns:
    df['tt_air_avg'] = pd.to_numeric(df['tt_air_avg'].astype(str).str.replace(',', '.'), errors='coerce')
