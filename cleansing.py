import pandas as pd

# Baca file
df = pd.read_csv(
    '/content/DATA_AWS_TANGSEL_BERSIH.csv',
    sep=';'
)

# Konversi datetime
df['tgl_data'] = pd.to_datetime(
    df['tgl_data'],
    errors='coerce'
)

# Urutkan waktu
df = df.sort_values('tgl_data')

# Ambil tanggal saja
df['tanggal'] = df['tgl_data'].dt.date

hasil = []

for tanggal, grup in df.groupby('tanggal'):

    # Cari jam 00:00:00
    jam_00 = grup[
        (grup['tgl_data'].dt.hour == 0) &
        (grup['tgl_data'].dt.minute == 0) &
        (grup['tgl_data'].dt.second == 0)
    ]

    if len(jam_00) > 0:
        hasil.append(jam_00.iloc[0])
    else:
        # Ambil record terakhir pada hari tersebut
        hasil.append(grup.iloc[-1])

df_perhari = pd.DataFrame(hasil)

# Hapus kolom bantu
df_perhari = df_perhari.drop(columns=['tanggal'])

print("Jumlah data awal :", len(df))
print("Jumlah data per hari :", len(df_perhari))

# Simpan
df_perhari.to_csv(
    'DATA_AWS_TANGSEL_PERHARI.csv',
    sep=';',
    index=False
)

